import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const output = new URL('../js/vendor/tokenizer/', import.meta.url);
await mkdir(output, { recursive: true });
const entries = { engine: 'js-tiktoken/lite', cl100k_base: 'js-tiktoken/ranks/cl100k_base', o200k_base: 'js-tiktoken/ranks/o200k_base' };
const files = {};
for (const [name, entry] of Object.entries(entries)) {
  const target = new URL(name + '.js', output);
  await build({ entryPoints: [entry], outfile: fileURLToPath(target), bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true, legalComments: 'none', banner: { js: '// js-tiktoken 1.0.21 (MIT). See NOTICES.txt. Generated by npm run vendor:tokenizer.' } });
  const bytes = await readFile(target);
  files[name + '.js'] = { bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') };
}
await writeFile(new URL('manifest.json', output), JSON.stringify({ package: 'js-tiktoken', version: '1.0.21', upstreamCommit: '4c8b748e07992c00386f3180af5c574b27b65139', bundler: 'esbuild 0.28.2', files }, null, 2) + '\n');
